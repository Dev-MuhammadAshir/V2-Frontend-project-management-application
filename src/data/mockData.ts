const now = new Date();
const daysAgo = (days: number, hours = 0) =>
  new Date(now.getTime() - (days * 24 + hours) * 60 * 60 * 1000).toISOString();
const daysFromNow = (days: number, hours = 0) =>
  new Date(now.getTime() + (days * 24 + hours) * 60 * 60 * 1000).toISOString();
